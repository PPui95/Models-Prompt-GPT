function bazi(y,m,d,hour){
  const beforeLichun=(m<2)||(m===2&&d<4);
  const by=beforeLichun?y-1:y;
  const ys=((by-4)%10+10)%10, yb=((by-4)%12+12)%12;
  let mi=m-2; if(d<TERM_DAY[m-1]) mi-=1; mi=(mi+12)%12;
  const ms=((ys%5)*2+2+mi)%10, mb=(mi+2)%12;
  const di=(jdn(y,m,d)+49)%60;
  let hp=null;
  if(hour!=null){const hb=Math.floor((hour+1)/2)%12; hp=[((di%10%5)*2+hb)%10,hb];}
  return {year:[ys,yb],month:[ms,mb],day:[di%10,di%12],hour:hp,by,y,m,d};
}
function analyse(b){
  const parts=[b.year,b.month,b.day,b.hour].filter(Boolean);
  const cnt=[0,0,0,0,0];
  parts.forEach(([s,br])=>{cnt[stemEl(s)]++;cnt[BR_EL[br]]++;});
  const dmE=stemEl(b.day[0]), resE=(dmE+4)%5;
  const w=[...cnt]; w[BR_EL[b.month[1]]]++; // month branch counts double (得令)
  const support=w[dmE]+w[resE], total=parts.length*2+1;
  const strong=support>total/2;
  const fav=strong?[(dmE+1)%5,(dmE+2)%5]:[resE,dmE];
  const unfav=strong?[resE,dmE]:[(dmE+3)%5,(dmE+2)%5];
  // ten-god profile: visible stems except the day master + main hidden stem of every branch
  const gods=[0,0,0,0,0], godIdx=Array(10).fill(0);
  const add=x=>{const g=tenGod(b.day[0],x);gods[g.rel]++;godIdx[g.idx]++;};
  parts.forEach(([,br])=>add(HIDDEN[br][0]));
  [b.year,b.month,b.hour].filter(Boolean).forEach(([s])=>add(s));
  return {cnt,dmE,support,total,strong,fav,unfav,gods,godIdx,parts};
}
